def raw_text(node,file):
    if not ue.new_object(ue.find_class("ObjectExporterT3D")).export_to_file(node,str(file)):raise RuntimeError("native localized node export failed")
    # The original FText stays on its original native pin. Never use the SDK's
    # string-only DefaultTextValue setter, which constructs FText::FromString.
    values=re.findall(r'DefaultTextValue=(.*?)(?=,(?:AutogeneratedDefaultValue|DefaultObject|LinkedTo|PersistentGuid|bHidden|bNotConnectable|bDefaultValueIsReadOnly|bDefaultValueIsIgnored|bAdvancedView|bOrphanedPin)=|\s*$)',file.read_text(encoding="utf-8-sig"),re.M)
    if not values:raise RuntimeError("native localized pin identity was not exported: "+str(file))
    return values


def set_asset(bp,name,module,cls):
    factory=DataAssetFactory();factory.DataAssetClass=UEPPythonMixinSet
    asset=ue.create_asset(name,"/Game/UEPMixins",UEPPythonMixinSet,factory);asset.DefaultProfile="Python"
    asset.Profiles=[UEPPythonMixinProfile(ProfileName=p,PythonModule=module,PythonClass=cls+p+"Profile") for p in ("Python","BlueprintFallback")]
    ue.blueprint_configure_mixin(bp,asset,"Python","PythonMixinProfile");return asset


def method_counts(bp,count):
    try:
        ue.register_declared_mixin(bp.GeneratedClass);row,=[r for r in ue.get_registered_mixins() if r["target_class"]==bp.GeneratedClass]
        value={name:len(r["functions"]) for name,r in row["profiles"].items()}
        if value!=dict(Python=count,BlueprintFallback=count):raise RuntimeError("complete message Profile family differs")
        return value
    finally:ue.unregister_all_mixins()


def move_node(source,target,node):
    guid=ue.find_struct("Guid")(**node.NodeGuid.as_dict());rooted=node.is_rooted()
    if not rooted:node.add_to_root()
    try:
        for pin in node.node_pins():
            for other in list(pin.get_linked_to()):pin.break_link_to(other)
        source.graph_remove_node(node);target.graph_add_node(node);node.NodeGuid=guid
    finally:
        if not rooted:node.remove_from_root()


def generate(stage):
    official=Path(json.loads((stage/".uep-lyra-full-stage.json").read_text(encoding="utf-8-sig"))["source"]).parent
    output=Path(next(a.split("=",1)[1] for a in __import__('sys').argv if a.startswith("-UEPHeroAbilityAssetsResult="))).parent
    for relative in (MATCH_REL,WAITING_REL):
        if hashlib.sha256((stage/relative).read_bytes()).digest()!=hashlib.sha256((official/relative).read_bytes()).digest():raise RuntimeError("fresh original message widgets required")
    ue.unregister_all_mixins();match=ue.load_object(Blueprint,MATCH.removesuffix("_C"));waiting=ue.load_object(Blueprint,WAITING.removesuffix("_C"));ue.unregister_all_mixins()
    before={label:snapshot(bp,label+"-message-before") for label,bp in (("match",match),("waiting",waiting))}
    signatures={"match":{n:ue.describe_function(match.GeneratedClass,n) for n in ("SetTeamMaterials","ConstructFromCueParams","PreConstruct")},
        "waiting":{"OnInitialized":ue.describe_function(waiting.GeneratedClass,"OnInitialized")}}
    originals={label:[(g,{n.get_name() for n in g.Nodes}) for g in ue.blueprint_get_all_graphs(bp)] for label,bp in (("match",match),("waiting",waiting))}
    if [sum(len(keys) for _,keys in originals[label]) for label in ("match","waiting")]!=[70,18]:raise RuntimeError("original message widget footprints differ")
    mg=match.UbergraphPages[0];mn={n.get_name():n for n in mg.Nodes};setters=[mn["K2Node_CallFunction_"+str(i)] for i in (13,4,14)]
    text_before={str(i):raw_text(n,output/("match-literal-"+str(i)+"-before.t3d")) for i,n in enumerate(setters)}
    ignored=set()
    for node in setters:
        target,=node.node_find_pin("then").get_linked_to();ignored.update(((node.get_name(),"then"),(target.owning_node.get_name(),target.name)))
    mh={g.get_name():semantics(g,keys,ignored if g==mg else set()) for g,keys in originals["match"]}
    make_gate(match,AFTER_TEXT,None);gate=next(g for g in ue.blueprint_get_all_graphs(match) if g.get_name()==AFTER_TEXT)
    gate.Nodes[0].node_create_pin(1,EdGraphPinType(PinCategory="int"),"Kind")
    for name,node in zip(TEXT_ENTRIES,setters):
        event=mg.graph_add_node(K2Node_CustomEvent);event.CustomFunctionName=name;mg.graph_reconstruct_node(event);connect(event,"then",node,"execute")
    ue.compile_blueprint(match);ue.unregister_all_mixins()
    for i,node in enumerate(setters):
        old={n.get_name() for n in mg.Nodes};insert_gate(mg,node,"then",getattr(match.GeneratedClass,AFTER_TEXT))
        call,=[n for n in mg.Nodes if n.get_name() not in old and n.get_class().get_name()=="K2Node_CallFunction"];call.node_find_pin("Kind").default_value=str(i)
    wg=waiting.UbergraphPages[0];wn={n.get_name():n for n in wg.Nodes}
    action=wn["K2Node_AsyncAction_ListenForGameplayMessages_0"];find=wn["K2Node_CallFunction_9"]
    if action.node_find_pin("Channel").default_value!='(TagName="ShooterGame.GamePhase.MatchBeginCountdown")' or action.node_find_pin("MatchType").default_value!="ExactMatch":raise RuntimeError("original waiting listener differs")
    moved=[wn[n] for n in ("K2Node_Select_0","K2Node_FormatText_0","K2Node_CallFunction_10","K2Node_VariableGet_2")]
    moved_names={n.get_name() for n in moved};wi={(find.get_name(),"then"),(action.get_name(),"execute"),(action.get_name(),"OnMessageReceived"),(wn["K2Node_IfThenElse_1"].get_name(),"execute")}
    moved_ignored={(moved[0].get_name(),"Index"),(moved[2].get_name(),"execute"),(moved[2].get_name(),"then")}
    wh={g.get_name():semantics(g,keys-moved_names,wi if g==wg else set()) for g,keys in originals["waiting"]}
    moved_hash=semantics(wg,moved_names,moved_ignored);waiting_text=raw_text(moved[0],output/"waiting-literals-before.t3d")
    setter=ue.blueprint_add_function(waiting,TEXT);entry=setter.Nodes[0];entry.node_create_pin(1,EdGraphPinType(PinCategory="int"),"Index");result=setter.graph_add_node(K2Node_FunctionResult)
    for node in moved:move_node(wg,setter,node)
    connect(entry,"then",moved[2],"execute");connect(entry,"Index",moved[0],"Index");connect(moved[0],"ReturnValue",moved[1],"Format")
    connect(moved[1],"Result",moved[2],"InText");connect(moved[3],"TeamNotification",moved[2],"self");connect(moved[2],"then",result,"execute")
    make_gate(waiting,MESSAGE,None)
    event=wg.graph_add_node(K2Node_CustomEvent);event.CustomFunctionName=LISTEN;wg.graph_reconstruct_node(event);connect(event,"then",action,"execute")
    ue.compile_blueprint(waiting);ue.unregister_all_mixins()
    call=wg.graph_add_node_call_function(getattr(waiting.GeneratedClass,TEXT));connect(find,"then",call,"execute");connect(wn["K2Node_CallFunction_0"],"ReturnValue",call,"Index");connect(call,"then",action,"execute")
    insert_gate(wg,action,"OnMessageReceived",getattr(waiting.GeneratedClass,MESSAGE))
    match_set=set_asset(match,"DA_MatchMessageMixin","uep_lyra_hud.match_message_mixin","LyraMatchMessage")
    waiting_set=set_asset(waiting,"DA_WaitingMessageMixin","uep_lyra_hud.waiting_message_mixin","LyraWaitingMessage")
    for bp in (match,waiting):ue.compile_blueprint(bp);ue.unregister_all_mixins()
    if int(match.Status)==2 or int(waiting.Status)==2:raise RuntimeError("message widget compile failed")
    for label,bp in (("match",match),("waiting",waiting)):
        if snapshot(bp,label+"-message-after")!=before[label] or any(ue.describe_function(bp.GeneratedClass,n)!=value for n,value in signatures[label].items()):raise RuntimeError("message full CDO/tree/event signatures changed")
    if any(semantics(g,keys,ignored if g==mg else set())!=mh[g.get_name()] for g,keys in originals["match"]):raise RuntimeError("original match business graph changed beyond literal dispatch")
    if any(semantics(g,keys-moved_names,wi if g==wg else set())!=wh[g.get_name()] for g,keys in originals["waiting"]) or semantics(setter,moved_names,moved_ignored)!=moved_hash:raise RuntimeError("original waiting graph/data nodes changed beyond typed transports")
    if any(raw_text(n,output/("match-literal-"+str(i)+"-after.t3d"))!=text_before[str(i)] for i,n in enumerate(setters)) or raw_text(moved[0],output/"waiting-literals-after.t3d")!=waiting_text:raise RuntimeError("native localized literal text changed")
    counts={"match":method_counts(match,3),"waiting":method_counts(waiting,2)}
    additions={label:sum(len(g.Nodes) for g in ue.blueprint_get_all_graphs(bp))-total for label,bp,total in (("match",match,70),("waiting",waiting,18))}
    interfaces={label:sum(len(g.Nodes) for g in ue.blueprint_get_all_graphs(bp) if g.get_name() in ("GetPythonMixinSet","GetPythonMixinProfile")) for label,bp in (("match",match),("waiting",waiting))}
    if additions!={"match":11+interfaces["match"],"waiting":8+interfaces["waiting"]}:raise RuntimeError("message transport footprints differ: "+str(additions))
    probe=ue.create_blueprint(ue.find_class("Object"),"/Game/UEPValidation/BP_MessageWidgetProbe")
    broadcast_graph(probe,"Verb",ue.find_struct("LyraVerbMessage"),ue.find_class("GameplayMessageSubsystem"));ue.compile_blueprint(probe)
    if int(probe.Status)==2:raise RuntimeError("typed countdown message probe failed")
    for asset in (match,waiting,match_set,waiting_set,probe):asset.save_package()
    return dict(status="passed",kind="messagewidgets",runtime_acceptance=False,full_acceptance=False,original_class_defaults_signature_graphs_preserved=True,
        original_full_cdos_widget_trees_event_signatures_and_business_preserved=True,original_graph_nodes={"match":70,"waiting":18},original_localized_text_pins_retained=True,
        localized_text_roundtripped_through_python=False,localized_literal_setter_and_formatter_adapters=True,original_native_listener_node_and_exact_channel_reused=True,
        no_python_subscription_roots=True,transport_nodes={"match":11,"waiting":8},interface_nodes=interfaces,new_business_nodes=0,native_end_adapter_nodes=0,
        actual_registered_profile_method_counts=counts,caller_probe=dict(stage_only=True,asset=str(stage/PROBE),sha256=hashlib.sha256((stage/PROBE).read_bytes()).hexdigest()),
        assets=[MATCH_REL,WAITING_REL,*SETS])
